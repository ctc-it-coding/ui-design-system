// node gen-assets.js  -> writes TS data modules into tinicorn-ui from assets-full.json
const fs = require('fs');
const A = JSON.parse(fs.readFileSync(__dirname + '/assets-full.json', 'utf8'));
const ROOT = '/home/claude/tinicorn-ui/src/components/';
const HDR = '// AUTO-GENERATED by /home/claude/figparse/gen-assets.js from the Figma file. Do not edit.\n';
const kebab = (s) => s.toLowerCase().replace(/\+/g, '-').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const round1 = (s) => s.replace(/-?\d+\.\d+/g, (m) => { const v = +(+m).toFixed(1); return (m[0] === '-' && v >= 0 ? ' ' : '') + String(v); });
const cur = (s) => s.replace(/var\(--color-gray-900,#101828\)/g, 'currentColor');
const J = (o) => JSON.stringify(o);
const art = (x, f = (s) => s) => ({ w: x.w, h: x.h, body: f(x.body) });
// unique gradient ids per asset so they don't clash across assets
let uid = 0;
const uniq = (body) => { const ids = [...new Set([...body.matchAll(/id="([^"]+)"/g)].map((m) => m[1]))]; for (const id of ids) { const n = 'tn' + (uid++).toString(36); body = body.split(`"${id}"`).join(`"${n}"`).split(`#${id})`).join(`#${n})`); } return body; };

function write(file, content) { fs.mkdirSync(require('path').dirname(file), { recursive: true }); fs.writeFileSync(file, HDR + content); console.log(file, Math.round(content.length / 1024) + 'KB'); }

// ---- company logos
{
  const out = {};
  for (const [v, x] of Object.entries(A['Fictional company logo'])) {
    const m = /Company=(.*), Logotype=(True|False), White=(True|False)/.exec(v); const k = kebab(m[1]);
    const slot = (m[2] === 'True' ? 'logotype' : 'mark') + (m[3] === 'True' ? 'White' : '');
    (out[k] ||= { label: m[1] })[slot] = { ...art(x, (b) => uniq(round1(b))), ...(x.op < 1 ? { op: x.op } : {}) };
  }
  const names = Object.keys(out);
  write(ROOT + 'logos/data/companyLogos.data.ts',
    `export type CompanyLogoName = ${names.map((n) => `'${n}'`).join(' | ')};\nexport interface LogoArt { w: number; h: number; body: string; op?: number }\nexport const companyLogoData: Record<CompanyLogoName, { label: string; logotype: LogoArt; mark: LogoArt; logotypeWhite: LogoArt; markWhite: LogoArt }> = ${J(out)};\n`);
}
// ---- press logos
{
  const out = {};
  for (const [v, x] of Object.entries(A['Press logo'])) { const n = v.replace('Company=', ''); out[kebab(n.replace(/^The /, ''))] = { label: n, ...art(x, (b) => round1(b).replace(/var\(--color-gray-700,#344054\)/g, 'currentColor')) }; }
  write(ROOT + 'logos/data/pressLogos.data.ts', `export type PressLogoName = ${Object.keys(out).map((n) => `'${n}'`).join(' | ')};\nexport const pressLogoData: Record<PressLogoName, { label: string; w: number; h: number; body: string }> = ${J(out)};\n`);
}
// ---- tinicorn logo
{
  const L = A['Logo']; const out = { light: art(L['Dark mode=False'], uniq), dark: art(L['Dark mode=True'], uniq), mark: art(A['Logomark']['Logomark'] || Object.values(A['Logomark'])[0], uniq) };
  write(ROOT + 'logos/data/tinicornLogo.data.ts', `export const tinicornLogoData: Record<'light' | 'dark' | 'mark', { w: number; h: number; body: string }> = ${J(out)};\n`);
}
// ---- app store badges
{
  const out = {};
  for (const [v, x] of Object.entries(A['Mobile app store badge'])) {
    const m = /Store=(.*), Style=(.*), Size=(md|lg)/.exec(v); out[`${kebab(m[1])}/${kebab(m[2])}/${m[3]}`] = art(x, (b) => uniq(round1(b)));
  }
  write(ROOT + 'buttons/appStoreBadges.data.ts', `/** key = store/style/size */\nexport const appStoreBadgeData: Record<string, { w: number; h: number; body: string }> = ${J(out)};\n`);
}
// ---- decorations
{
  const pick = (set, re) => { const o = {}; for (const [v, x] of Object.entries(A[set])) o[kebab(v.replace(re, ''))] = art(x, (b) => cur(round1(b))); return Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b))); };
  const arrows = pick('Hand-drawn arrow', /^Arrow=/), underlines = pick('Hand-drawn underlines', /^Underline=/), accents = pick('Hand-drawn accents', /^Accent=/), scribbles = pick('Hand-drawn pen scribble', /^Pen scribble=/), lines = pick('Hand-drawn line', /^Style=Line, Line=/);
  const T = (n, o) => `export type ${n} = ${Object.keys(o).map((k) => `'${k}'`).join(' | ')};\n`;
  write(ROOT + 'decorations/data/handDrawn.data.ts',
    `export interface Art { w: number; h: number; body: string }\n` + T('HandDrawnArrowVariant', arrows) + T('HandDrawnUnderlineVariant', underlines) + T('HandDrawnAccentVariant', accents) + T('PenScribbleVariant', scribbles) + T('HandDrawnLineVariant', lines) +
    `export const arrowData: Record<HandDrawnArrowVariant, Art> = ${J(arrows)};\nexport const underlineData: Record<HandDrawnUnderlineVariant, Art> = ${J(underlines)};\nexport const accentData: Record<HandDrawnAccentVariant, Art> = ${J(accents)};\nexport const scribbleData: Record<PenScribbleVariant, Art> = ${J(scribbles)};\nexport const lineData: Record<HandDrawnLineVariant, Art> = ${J(lines)};\n`);
}
// ---- line patterns
{
  const o = {}; for (const [v, x] of Object.entries(A['Line pattern'])) o[kebab(v.replace('Style=', ''))] = art(x, (b) => cur(round1(b)));
  write(ROOT + 'backgrounds/data/linePatterns.data.ts', `export type LinePatternStyle = ${Object.keys(o).map((k) => `'${k}'`).join(' | ')};\nexport const linePatternData: Record<LinePatternStyle, { w: number; h: number; body: string }> = ${J(o)};\n`);
}
