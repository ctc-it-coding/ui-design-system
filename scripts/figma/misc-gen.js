walkP(page);
const kebab = (s) => s.replace(/\(.*?\)/g, '').trim().replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase();
const props = (name) => Object.fromEntries(name.split(', ').map(p => p.split('=')));
