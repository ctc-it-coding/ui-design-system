const blob = (i) => Buffer.from(msg.blobs[i], 'base64');
const R = (v) => +v.toFixed(2);
function mul(A, B) { return { a: A.a * B.a + A.c * B.b, b: A.b * B.a + A.d * B.b, c: A.a * B.c + A.c * B.d, d: A.b * B.c + A.d * B.d, e: A.a * B.e + A.c * B.f + A.e, f: A.b * B.e + A.d * B.f + A.f }; }
const fromT = (t) => t ? { a: t.m00, b: t.m10, c: t.m01, d: t.m11, e: t.m02, f: t.m12 } : { a: 1, b: 0, c: 0, d: 1, e: 0, f: 0 };
const ap = (M, x, y) => [R(M.a * x + M.c * y + M.e), R(M.b * x + M.d * y + M.f)];
function geomPath(n, which, M) {
  const g = n[which]; if (!g || !g.length) return null; let d = '';
  for (const gg of g) { const b = blob(gg.commandsBlob); let o = 0; const f = () => { const v = b.readFloatLE(o); o += 4; return v; };
    while (o < b.length) { const c = b[o++]; if (c === 0) d += 'Z'; else if (c === 1) d += 'M' + ap(M, f(), f()).join(' '); else if (c === 2) d += 'L' + ap(M, f(), f()).join(' '); else if (c === 3) { const a = ap(M, f(), f()), e = ap(M, f(), f()); d += `Q${a.join(' ')} ${e.join(' ')}`; } else if (c === 4) { const a = ap(M, f(), f()), bb = ap(M, f(), f()), e = ap(M, f(), f()); d += `C${a.join(' ')} ${bb.join(' ')} ${e.join(' ')}`; } else break; } }
  return d.replace(/ -/g, '-');
}
const styleNode = (ref, prop) => { if (!ref) return null; const g = ref.guid && nodes.get(key(ref.guid)); if (g && g[prop]) return g; const k = ref.assetRef?.key; if (k) { for (const n of nodes.values()) if (n.key === k && n[prop]) return n; } return null; };
const fills = (n) => { const s = styleNode(n.styleIdForFill, 'fillPaints'); return s ? s.fillPaints : n.fillPaints; };
const strokes = (n) => { const s = styleNode(n.styleIdForStrokeFill, 'fillPaints'); return s ? s.fillPaints : n.strokePaints; };
const hx = (c, o = 1) => { const a = (c.a ?? 1) * o; return '#' + [c.r, c.g, c.b].map(v => Math.round(v * 255).toString(16).padStart(2, '0')).join('') + (a < 0.999 ? Math.round(a * 255).toString(16).padStart(2, '0') : ''); };
function paintColor(ps) { const p = (ps || []).filter(p => p.visible !== false && (p.opacity ?? 1) > 0); if (!p.length) return null; const t = p[p.length - 1]; if (t.type === 'SOLID') return hx(t.color, t.opacity ?? 1); if (t.stops) return hx(t.stops[0].color, t.opacity ?? 1); return null; }
const SHAPES = /^(VECTOR|ELLIPSE|ROUNDED_RECTANGLE|RECTANGLE|LINE|STAR|REGULAR_POLYGON|BOOLEAN_OPERATION)$/;
/** Colored SVG of a node subtree; `skip(n)` returns true to omit a node, `mono` replaces colors with currentColor. */
function svgOf(root, { skip = () => false, mono = false, origin = null } = {}) {
  const parts = [];
  const walk = (n, M) => {
    if (n.visible === false || skip(n)) return;
    const T = n === root ? (origin || { a: 1, b: 0, c: 0, d: 1, e: 0, f: 0 }) : mul(M, fromT(n.transform));
    const op = n.opacity !== undefined && n.opacity < 1 ? ` opacity="${R(n.opacity)}"` : '';
    if (n !== root && SHAPES.test(n.type)) {
      const fc = paintColor(fills(n)); const sc = n.strokeWeight > 0 ? paintColor(strokes(n)) : null;
      const col = (c) => mono ? 'currentColor' : c;
      if (fc) { const d = geomPath(n, 'fillGeometry', T); if (d) parts.push(`<path d="${d}" fill="${col(fc)}"${op}${n.fillGeometry?.[0]?.windingRule === 'ODD' ? ' fill-rule="evenodd"' : ''}/>`); }
      if (sc) { const d = geomPath(n, 'strokeGeometry', T); if (d) parts.push(`<path d="${d}" fill="${col(sc)}"${op}/>`); }
      return;
    }
    if (n !== root && (n.type === 'FRAME' || n.type === 'INSTANCE' || n.type === 'SYMBOL')) {
      const fc = paintColor(fills(n));
      if (fc && n.size) { const [x, y] = ap(T, 0, 0); parts.push(`<rect x="${x}" y="${y}" width="${R(n.size.x)}" height="${R(n.size.y)}" rx="${n.cornerRadius || 0}" fill="${mono ? 'currentColor' : fc}"${op}/>`); }
    }
    for (const c of n._children) walk(c, T);
  };
  walk(root, null);
  return parts.join('');
}
const page = [...nodes.values()].find(n => n.type === 'CANVAS' && n.name.includes('↳ Misc icons'));
const sets = {}; const singles = {};
